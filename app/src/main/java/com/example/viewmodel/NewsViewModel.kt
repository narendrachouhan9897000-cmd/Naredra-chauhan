package com.example.viewmodel

import androidx.lifecycle.ViewModel
import androidx.lifecycle.viewModelScope
import com.example.data.NewsRepository
import com.example.model.AutoUploadStatus
import com.example.model.BreakingTickerItem
import com.example.model.LiveChatMessage
import com.example.model.NewsCategory
import com.example.model.NewsVideo
import kotlinx.coroutines.Job
import kotlinx.coroutines.delay
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.SharingStarted
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.asStateFlow
import kotlinx.coroutines.flow.combine
import kotlinx.coroutines.flow.stateIn
import kotlinx.coroutines.launch

sealed class ScreenDestination {
    object Home : ScreenDestination()
    object Live : ScreenDestination()
    object Shorts : ScreenDestination()
    object Saved : ScreenDestination()
    object Studio : ScreenDestination()
    data class Detail(val video: NewsVideo) : ScreenDestination()
}

class NewsViewModel(
    private val repository: NewsRepository = NewsRepository()
) : ViewModel() {

    private val _currentScreen = MutableStateFlow<ScreenDestination>(ScreenDestination.Home)
    val currentScreen: StateFlow<ScreenDestination> = _currentScreen.asStateFlow()

    private val _selectedCategory = MutableStateFlow(NewsCategory.ALL)
    val selectedCategory: StateFlow<NewsCategory> = _selectedCategory.asStateFlow()

    private val _searchQuery = MutableStateFlow("")
    val searchQuery: StateFlow<String> = _searchQuery.asStateFlow()

    private val _autoUploadFeedback = MutableStateFlow<String?>(null)
    val autoUploadFeedback: StateFlow<String?> = _autoUploadFeedback.asStateFlow()

    val rawVideos = repository.videos
    val autoUploadStatus: StateFlow<AutoUploadStatus> = repository.autoUploadStatus
    val liveChat: StateFlow<List<LiveChatMessage>> = repository.liveChat
    val tickerItems: StateFlow<List<BreakingTickerItem>> = repository.tickerItems

    val filteredVideos: StateFlow<List<NewsVideo>> = combine(
        rawVideos,
        _selectedCategory,
        _searchQuery
    ) { videos, category, query ->
        videos.filter { video ->
            val matchesCategory = (category == NewsCategory.ALL) || (video.category == category)
            val matchesQuery = query.isBlank() ||
                    video.title.contains(query, ignoreCase = true) ||
                    video.summary.contains(query, ignoreCase = true) ||
                    video.anchorName.contains(query, ignoreCase = true)
            matchesCategory && matchesQuery
        }
    }.stateIn(viewModelScope, SharingStarted.WhileSubscribed(5000), emptyList())

    val liveVideo: StateFlow<NewsVideo?> = rawVideos.combine(rawVideos) { videos, _ ->
        videos.firstOrNull { it.isLive }
    }.stateIn(viewModelScope, SharingStarted.WhileSubscribed(5000), null)

    private var autoDaemonJob: Job? = null

    private val autoGeneratedHeadlines = listOf(
        Pair("Global Clean Energy Grid Reaches 50% Milestone Ahead of Schedule", NewsCategory.CLIMATE),
        Pair("Breakthrough in Solid-State Battery Tech Unlocks 1,000-Mile EV Range", NewsCategory.TECH),
        Pair("International Space Station Crew Tests Holographic Telepresence Link", NewsCategory.SCIENCE),
        Pair("Central Banks Launch Real-Time Cross-Border Digital Settlement System", NewsCategory.MARKETS),
        Pair("Deep Ocean Submersible Discovers Hydrothermal Coral Ecosystem", NewsCategory.SCIENCE),
        Pair("Autonomous Flying Ambulance Fleet Completes 500 Emergency Sorties", NewsCategory.TECH),
        Pair("Global Food Security Summit Approves Drought-Resistant Bio-Seeds", NewsCategory.WORLD)
    )
    private var headlineIndex = 0

    init {
        startAutoUploadDaemon()
    }

    private fun startAutoUploadDaemon() {
        autoDaemonJob?.cancel()
        autoDaemonJob = viewModelScope.launch {
            while (true) {
                delay(40_000) // Auto-dispatches every 40s in background
                if (autoUploadStatus.value.isRunning) {
                    val nextItem = autoGeneratedHeadlines[headlineIndex % autoGeneratedHeadlines.size]
                    headlineIndex++
                    val uploaded = repository.simulateManualAutoUpload(
                        title = nextItem.first,
                        category = nextItem.second,
                        summary = "Continuous automated newsroom dispatch ingested from international satellite wire.",
                        anchor = "AI Anchor Pulse-Bot",
                        onStageUpdate = { /* background */ }
                    )
                    _autoUploadFeedback.value = "New video auto-uploaded: ${uploaded.title.take(35)}..."
                    delay(4000)
                    _autoUploadFeedback.value = null
                }
            }
        }
    }

    fun navigateTo(destination: ScreenDestination) {
        _currentScreen.value = destination
    }

    fun selectCategory(category: NewsCategory) {
        _selectedCategory.value = category
    }

    fun updateSearchQuery(query: String) {
        _searchQuery.value = query
    }

    fun toggleSave(videoId: String) {
        repository.toggleSaveVideo(videoId)
    }

    fun toggleLike(videoId: String) {
        repository.toggleLikeVideo(videoId)
    }

    fun sendLiveComment(message: String) {
        if (message.isNotBlank()) {
            repository.sendLiveComment(message.trim())
        }
    }

    fun triggerManualUpload(
        title: String,
        category: NewsCategory,
        summary: String,
        anchor: String,
        onStageUpdate: (String) -> Unit,
        onComplete: (NewsVideo) -> Unit
    ) {
        viewModelScope.launch {
            val video = repository.simulateManualAutoUpload(
                title = title,
                category = category,
                summary = summary,
                anchor = anchor,
                onStageUpdate = onStageUpdate
            )
            onComplete(video)
        }
    }

    fun toggleAutoDaemon(enabled: Boolean) {
        repository.toggleAutoDaemon(enabled)
    }

    fun dismissFeedback() {
        _autoUploadFeedback.value = null
    }
}
